import type { Request, Response, NextFunction } from "express";
import { HttpException } from "@/utils/http.exception";
import { DomainError } from "@/shared/errors/domain.error";

/**
 * The single domain → HTTP mapping. Layers below the boundary throw domain
 * errors; only this table knows what they mean over HTTP.
 */
const STATUS_BY_DOMAIN_CODE: Record<string, number> = {
  NOT_FOUND: 404,
  FORBIDDEN: 403,
  CONFLICT: 409,
  VALIDATION: 422,
  PERSISTENCE: 500,
};

export function errorMiddleware(error: Error, req: Request, res: Response, _next: NextFunction): void {
  let statusCode = 500;
  let message = "An unexpected internal server error occurred";
  let details: unknown = null;

  if (error instanceof DomainError) {
    statusCode = STATUS_BY_DOMAIN_CODE[error.code] ?? 500;
    message = error.message;
    details = error.details;
  } else if (error instanceof HttpException) {
    // Boundary-level failures that are genuinely about HTTP (zod validation in
    // `validate`) still carry their own status.
    statusCode = error.statusCode;
    message = error.message;
    details = error.details;
  }

  // pino-http attaches a per-request child logger (tagged with a request id).
  const log = req.log;

  // Log every server-side failure (5xx) with the full error — including the
  // preserved `cause` chain — so nothing is silently swallowed. Client errors
  // (4xx) are expected/operational and already captured by request logging.
  if (statusCode >= 500) {
    log.error({ err: error }, `💥 ${req.method} ${req.url} failed (500)`);
  }

  res.status(statusCode).json({
    success: false,
    message,
    ...(details !== null ? { details } : {}), // Validation details array if generated by Zod
    timestamp: new Date().toISOString(),
  });
}
